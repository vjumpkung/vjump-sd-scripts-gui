"""Argument schema of the sd-scripts training scripts.

The schema is generated by ``app/sdscripts/dump_args.py`` running under the
sd-scripts virtualenv. A bundled snapshot ships with the app so the UI works
before (or without) a local sd-scripts checkout.

Selection order:

1. ``data/schema.json`` when its commit equals the checkout's HEAD;
2. the bundled snapshot when its commit equals HEAD;
3. otherwise the bundled snapshot is served with ``stale = true`` and one
   background regeneration is started (when the sd-scripts python exists).

A checkout without a readable commit uses ``data/schema.json`` when present and
otherwise regenerates in the background, serving the bundled snapshot meanwhile.
"""

from __future__ import annotations

import asyncio
import contextlib
import json
import os
import subprocess
from pathlib import Path
from typing import Any

from ..config import Settings
from ..utils.process import child_env, terminate_tree

SDSCRIPTS_DIR = Path(__file__).resolve().parent.parent / "sdscripts"
BUNDLED_SNAPSHOT = SDSCRIPTS_DIR / "args_snapshot.json"
DUMP_SCRIPT = SDSCRIPTS_DIR / "dump_args.py"
RESCAN_TIMEOUT_SECONDS = 600
GIT_TIMEOUT_SECONDS = 10


class RescanError(Exception):
    """A rescan request that cannot start (HTTP status in ``status``)."""

    def __init__(self, status: int, message: str):
        super().__init__(message)
        self.status = status


def _load_snapshot(path: Path) -> dict[str, Any] | None:
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return None
    if not isinstance(data, dict) or not isinstance(data.get("scripts"), dict):
        return None
    if not isinstance(data.get("errors"), dict):
        data["errors"] = {}
    return data


def _git_head(sd_dir: Path) -> str | None:
    if not (sd_dir / ".git").exists():
        return None
    try:
        completed = subprocess.run(
            ["git", "-C", str(sd_dir), "rev-parse", "HEAD"],
            capture_output=True,
            text=True,
            timeout=GIT_TIMEOUT_SECONDS,
            check=False,
        )
    except (OSError, subprocess.SubprocessError):
        return None
    commit = completed.stdout.strip()
    return commit if completed.returncode == 0 and commit else None


class ArgSchemaService:
    def __init__(self, settings: Settings):
        self.settings = settings
        self.bundled = _load_snapshot(BUNDLED_SNAPSHOT)
        self.generated: dict[str, Any] | None = None
        # Cached `git rev-parse HEAD`; refreshed at startup and after a rescan.
        self.sd_commit: str | None = None
        self.rescan_state = "idle"  # idle | running | failed
        self.rescan_error: str | None = None
        self._task: asyncio.Task[None] | None = None
        self._process: asyncio.subprocess.Process | None = None
        self._auto_attempted = False

    # ---- lifecycle -------------------------------------------------------

    async def start(self) -> None:
        await self.refresh_commit()
        self.generated = _load_snapshot(self.settings.schema_path)
        self._maybe_auto_regenerate()

    async def shutdown(self) -> None:
        task = self._task
        if task is not None and not task.done():
            task.cancel()
            with contextlib.suppress(asyncio.CancelledError):
                await task
        if self._process is not None:
            await terminate_tree(self._process)

    async def refresh_commit(self) -> None:
        self.sd_commit = await asyncio.to_thread(_git_head, self.settings.sd_dir)

    # ---- selection -------------------------------------------------------

    def _active(self) -> tuple[dict[str, Any] | None, str, bool]:
        """Return ``(snapshot, source, stale)`` for the currently served schema."""
        commit = self.sd_commit
        generated, bundled = self.generated, self.bundled
        if commit is not None:
            if generated is not None and generated.get("commit") == commit:
                return generated, "generated", False
            if bundled is not None and bundled.get("commit") == commit:
                return bundled, "bundled", False
            return bundled, "bundled", True
        if generated is not None:
            return generated, "generated", False
        return bundled, "bundled", False

    def _needs_regeneration(self) -> bool:
        _, source, stale = self._active()
        if self.sd_commit is not None:
            return stale
        return self.generated is None and source == "bundled"

    def _maybe_auto_regenerate(self) -> None:
        """Start one background regeneration when the served schema is stale."""
        if self._auto_attempted or not self._needs_regeneration():
            return
        if not self.settings.sd_python_ok or not self.settings.sd_dir.is_dir():
            return
        self._auto_attempted = True
        self.rescan_state = "running"
        self._task = asyncio.create_task(self._regenerate())

    def status(self) -> dict[str, Any]:
        snapshot, source, stale = self._active()
        return {
            "source": source,
            "commit": snapshot.get("commit") if snapshot else None,
            "stale": stale,
            "rescan": {"state": self.rescan_state, "error": self.rescan_error},
        }

    # ---- lookups ---------------------------------------------------------

    def get_script(self, script: str) -> dict[str, Any] | None:
        """Return ``{script, commit, source, args}`` or None when unavailable.

        A script with a generation error falls back to the bundled entry.
        """
        snapshot, source, _ = self._active()
        entry = None
        if snapshot is not None and script not in snapshot.get("errors", {}):
            entry = snapshot["scripts"].get(script)
        if entry is None and self.bundled is not None:
            fallback = self.bundled["scripts"].get(script)
            if fallback is not None:
                snapshot, source, entry = self.bundled, "bundled", fallback
        if entry is None or snapshot is None:
            return None
        return {
            "script": script,
            "commit": snapshot.get("commit"),
            "source": source,
            "args": entry["args"],
        }

    # ---- regeneration ----------------------------------------------------

    async def rescan(self) -> None:
        if self.rescan_state == "running":
            raise RescanError(409, "A rescan is already running")
        if not self.settings.sd_python_ok:
            raise RescanError(503, "The sd-scripts Python environment was not found")
        if not self.settings.sd_dir.is_dir():
            raise RescanError(503, "The sd-scripts directory was not found")
        self.rescan_state = "running"
        self.rescan_error = None
        self._task = asyncio.create_task(self._regenerate())

    async def _regenerate(self) -> None:
        self.rescan_state = "running"
        self.rescan_error = None
        settings = self.settings
        temporary = settings.schema_path.with_name(settings.schema_path.name + ".tmp")
        try:
            settings.data_root.mkdir(parents=True, exist_ok=True)
            temporary.unlink(missing_ok=True)
            env = child_env(
                {
                    "PYTHONDONTWRITEBYTECODE": "1",
                    "PYTHONUTF8": "1",
                    "PYTHONUNBUFFERED": "1",
                }
            )
            kwargs: dict[str, Any] = {}
            if os.name == "nt":
                kwargs["creationflags"] = subprocess.CREATE_NEW_PROCESS_GROUP
            else:
                kwargs["start_new_session"] = True
            self._process = await asyncio.create_subprocess_exec(
                str(settings.sd_python),
                str(DUMP_SCRIPT),
                "--sd-scripts-dir",
                str(settings.sd_dir),
                "--out",
                str(temporary),
                cwd=str(settings.sd_dir),
                env=env,
                stdin=asyncio.subprocess.DEVNULL,
                stdout=asyncio.subprocess.DEVNULL,
                stderr=asyncio.subprocess.PIPE,
                **kwargs,
            )
            try:
                _, stderr = await asyncio.wait_for(
                    self._process.communicate(), timeout=RESCAN_TIMEOUT_SECONDS
                )
            except TimeoutError:
                await terminate_tree(self._process)
                raise RuntimeError(
                    f"Schema generation timed out after {RESCAN_TIMEOUT_SECONDS}s"
                ) from None
            if self._process.returncode != 0:
                tail = stderr.decode("utf-8", errors="replace").strip()[-1000:]
                raise RuntimeError(
                    "Schema generation failed"
                    + (f": {tail}" if tail else f" (exit {self._process.returncode})")
                )
            snapshot = _load_snapshot(temporary)
            if snapshot is None or not snapshot["scripts"]:
                raise RuntimeError("Schema generation produced no usable schema")
            os.replace(temporary, settings.schema_path)
            self.generated = snapshot
            await self.refresh_commit()
            self.rescan_state = "idle"
        except asyncio.CancelledError:
            self.rescan_state = "idle"
            raise
        except (OSError, RuntimeError) as error:
            self.rescan_state = "failed"
            self.rescan_error = str(error)[:1200]
        finally:
            self._process = None
            with contextlib.suppress(OSError):
                temporary.unlink(missing_ok=True)
